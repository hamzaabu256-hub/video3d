#!/usr/bin/env python3
"""يمسح src/story/episodes/* ويولّد src/story/registry.ts (يُستدعى تلقائياً من new_episode.py)."""
import pathlib, re
ROOT = pathlib.Path(__file__).resolve().parents[1]
eps = sorted(p.name for p in (ROOT / "src/story/episodes").iterdir() if (p / "story.json").exists())
bad = [e for e in eps if not re.fullmatch(r"[A-Za-z0-9-]+", e)]
assert not bad, f"أسماء الحلقات يجب أن تكون حروف/أرقام/شرطة فقط: {bad}"
v = lambda e: re.sub(r"\W", "_", e)
out = ["// AUTO-GENERATED by tools/gen_registry.py — لا تعدّله يدوياً", 'import type { EpisodeData } from "./types";']
for e in eps:
    for f in ("story", "timeline", "mouth"):
        out.append(f'import {v(e)}_{f} from "./episodes/{e}/{f}.json";')
out.append("export const EPISODES: Record<string, EpisodeData> = {")
for e in eps:
    out.append(f'  "{e}": {{ story: {v(e)}_story as any, timeline: {v(e)}_timeline as any, mouth: {v(e)}_mouth as any }},')
out.append("};")
(ROOT / "src/story/registry.ts").write_text("\n".join(out) + "\n", encoding="utf-8")
print("registry:", ", ".join(eps))
